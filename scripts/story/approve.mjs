// story:approve: ladder step 8, operator approval before publish.
//
//   pnpm story:approve <slug> --by "<your name>"
//
// The person who read the draft, looked at the illustration, and listened to
// the whole narration confirms it here, in their own terminal. It re-runs
// story:check, re-measures the image and MP3 from the files, and shows every
// identity on the record: who reviewed the draft and who signed the verdict
// off, who ran SEO QA and who signed that off, how the image and narration
// were made, and whether the transcript check passed. Then the operator types
// the slug.
//
// The approval (in content/drafts/<slug>/state.json) binds sha256 hashes of
// the draft, gate note, SEO note, illustration and MP3, and records the name
// typed with --by plus the OS account that ran it. Change any of those files
// and story:publish refuses until someone approves again.
//
// It refuses to run inside an agent session (Claude Code, bb threads). That and
// the typed slug are speed bumps, not security: anyone with a shell can fake a
// terminal or edit state.json. The approval record is advisory; the control
// that matters is the Basehub commit, which a person makes (see story:publish).

import { createInterface } from 'node:readline/promises'
import { userInfo } from 'node:os'
import { main, isEntry, log, c, GateError, UsageError, isAgentSession } from './lib/cli.mjs'
import { writeStage } from './lib/draft.mjs'
import { requireCheck } from './check.mjs'
import { imageArtifact, audioArtifact } from './lib/artifacts.mjs'

async function cli({ _, flags }) {
  const slug = _[0]
  if (isAgentSession()) {
    throw new GateError(`Approval is a person's step. Run \`pnpm story:approve ${slug} --by "<your name>"\` in your own terminal, outside the agent session.`)
  }
  if (!process.stdin.isTTY || !process.stdout.isTTY) {
    throw new GateError(`Approval needs an interactive terminal. Run \`pnpm story:approve ${slug} --by "<your name>"\` yourself.`)
  }
  if (!flags.by) throw new UsageError('Pass --by "<your name>" so the approval names the person who gave it.')
  const check = await requireCheck(slug)
  const { draft, gate, seo } = check
  const image = await imageArtifact(draft)
  const audio = await audioArtifact(draft)
  const problems = [...image.problems, ...audio.problems]
  if (problems.length) throw new GateError(problems.join(' '))

  const red = (s) => c.red(c.bold(s))
  console.log(c.bold(`\nApproving "${draft.fields.title}" (${slug}) for publish`))
  console.log(`  draft     content/drafts/${slug}.md  sha256 ${draft.hash.slice(0, 12)}`)
  console.log(`  editor    round ${gate.round} ${gate.verdict}; reviewed by ${gate.reviewer ?? '(not named)'}; signed off by ${gate.signOff.name} on ${gate.signOff.date}`)
  console.log(`  SEO QA    ${seo.verdict}; run by ${seo.runBy}; signed off by ${seo.signOff.name} on ${seo.signOff.date}`)
  console.log(`  image     ${image.file}  ${image.width}x${image.height}  ${image.provenance?.kind === 'generated' ? `generated by ${image.provenance.model}` : `supplied file ${image.provenance?.file ?? ''}`}`)
  console.log(`  alt       ${draft.fields.imageAlt}`)
  if (audio.expectation === 'none') console.log('  audio     none (draft says audio: "none")')
  else if (audio.expectation === 'url') console.log(`  audio     hosted: ${audio.url}`)
  else {
    console.log(`  audio     ${audio.file}  ${audio.report.durationISO}  ${audio.report.loudness.integrated} LUFS (${audio.report.loudnessDualMono.integrated} as heard)  ${audio.record.provider}${audio.record.voice?.voiceId ? ` voice ${audio.record.voice.voiceId}` : ''}`)
    console.log(`  pace      ${audio.pace.words} spoken words in ${audio.report.duration}s = ${audio.pace.wps} words/s`)
    console.log(`  transcript ${audio.transcript.status === 'pass' ? `matches the script (WER ${audio.transcript.wer})` : red(`NOT VERIFIED: ${audio.transcript.reason ?? audio.transcript.status}`)}`)
    if (audio.record.inputOverride) console.log(`  ${red('INPUT OVERRIDE: a recording replaced the planned TTS narration')}`)
    console.log(`  cover     embedded in the MP3; check the crop in any music player`)
  }
  for (const w of audio.warnings) console.log(`  ${red(w)}`)
  console.log(`  summary   ${draft.fields.summary}`)
  console.log(`  moral     ${draft.fields.virtueDescription}`)
  console.log(c.dim('\n  Approve only after reading the draft, looking at the image, and listening to the whole narration.'))

  const rl = createInterface({ input: process.stdin, output: process.stdout })
  const typed = (await rl.question(`\nType the slug to approve as ${flags.by}: `)).trim()
  rl.close()
  if (typed !== slug) throw new GateError('Slug did not match. Nothing approved.')

  writeStage(slug, 'approval', {
    status: 'pass',
    by: flags.by,
    osUser: userInfo().username,
    draftHash: draft.hash,
    gateHash: gate.hash,
    seoHash: seo.hash,
    imageSha256: image.sha256,
    audioSha256: audio.sha256 ?? null,
  })
  log.ok(`Approved by ${flags.by} (${userInfo().username}). Next (ladder step 9): pnpm story:publish ${slug}`)
}

if (isEntry(import.meta.url)) main(cli, { meta: import.meta.url, args: [1, 1], flags: { by: 'string' } })
